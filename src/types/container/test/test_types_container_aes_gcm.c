static Bool aesCreateCtx(
	Test *t, const C8 *label,
	I64 blockSizeHint, U8 cryptoSt,
	AESEncryptionKey key, AESEncryptionContext *ctx,
	U8 *blockSizeMax, U8 *use256Or512
) {
	if (!Buffer_aesExpertCreate(
		I32x4_zero(),
		EBufferEncryptionType_AES256GCM,
		key,
		blockSizeHint,
		0,
		cryptoSt,
		blockSizeMax,
		use256Or512,
		ctx,
		&t->err
	)) {
		Test_assert(t, label, false);
		return false;
	}

	return true;
}

void Test_aesValidation(Test *t) {

	Test_setModule(t, "aes256gcm validate batch sizes, crypto capabilities");

	const AESEncryptionKey key = { 0 };

	Buffer full = Buffer_createNull();

	if (!Buffer_createUninitializedBytes(65536 * 2, t->alloc, &full, &t->err)) {
		Test_assert(t, "Alloc full buffer", false);
		return;
	}

	Buffer_unsetAllBits(full, &t->err);

	for (U64 l = 0; l < sizeof(cryptoState) / sizeof(cryptoState[0]); ++l) {

		AESEncryptionContext ctx = { 0 };
		U8 blockSizeMax = 0, use256Or512 = 0;

		//Check whether this variant is supported
		if (!aesCreateCtx(t, "aesCreateCtx test", -16, cryptoState[l], key, &ctx, &blockSizeMax, &use256Or512))
			continue;

		if (use256Or512 != cryptoState[l])		//Hardware doesn't support this
			continue;

		for (U64 i = 0; i < sizeof(sizes) / sizeof(sizes[0]); ++i) {

			const U64    siz        = sizes[i];
			Buffer       unit       = Buffer_createRef(full.ptrNonConst, siz);
			const I32x4  tagExpect  = I32x4_load4((const void*)&tagForValidation[i]);

			//Encrypt

			if (!aesCreateCtx(t, "Enc aesCreateCtx", -16, cryptoState[l], key, &ctx, &blockSizeMax, &use256Or512))
				continue;

			Buffer_unsetAllBits(unit, &t->err);
			Buffer_aesExpertEncUpdate(&ctx, unit, 0, blockSizeMax, use256Or512);
			Buffer_aesExpertFinalize(&ctx, 0, siz, I32x4_zero());

			Test_assert(t, "Enc GMAC", !I32x4_neq4(ctx.tag, tagExpect));

			//Check first 4 KiB of ciphertext output matches precomputed reference.
			//(Tags and decrypt already cover the full range; this is an extra check in case AES fails but ghash succeeds)

			const Buffer ref  = Buffer_createRefConst(validationData, U64_min(sizeof(validationData), siz));
			const Buffer got  = Buffer_createRefConst(full.ptr,       U64_min(sizeof(validationData), siz));
			Test_assert(t, "Enc ciphertext", !Buffer_neq(got, ref));

			//Check AAD

			if (!aesCreateCtx(t, "AAD create", -16, cryptoState[l], key, &ctx, &blockSizeMax, &use256Or512))
				continue;

			Buffer_aesExpertUpdateAAD(&ctx, unit, blockSizeMax, use256Or512);
			Test_assert(t, "AAD GMAC", Buffer_aesExpertFinalize(&ctx, 0, siz, tagExpect));

			//Decrypt

			if (!aesCreateCtx(t, "Dec create", -16, cryptoState[l], key, &ctx, &blockSizeMax, &use256Or512))
				continue;

			Buffer_aesExpertDecUpdate(&ctx, unit, 0, blockSizeMax, use256Or512);
			Test_assert(t, "Dec GMAC", Buffer_aesExpertFinalize(&ctx, 0, siz, tagExpect));

			//Decrypting all-zeros with the same key/IV should yield all-zeros back

			Buffer zeroBuf = Buffer_createRef(full.ptrNonConst + siz, siz);
			Buffer_unsetAllBits(zeroBuf, &t->err);
			Test_assert(t, "Dec round-trip", !Buffer_neq(unit, zeroBuf));
		}
	}

	Buffer_free(&full, t->alloc);
}

