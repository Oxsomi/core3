//Shared loop used for both AES256 and AES128 test vectors.
//Each test vector is: encrypt -> verify ciphertext + tag -> decrypt -> verify plaintext.

static void runAesVectors(
	Test *t,
	EBufferEncryptionType type,
	U64 count,
	const CharString *keys,
	const CharString *plainTexts,
	const CharString *aad,
	const U8 (*ivBytes)[13],
	const CharString *results
) {
	CharString tmp = CharString_createNull();
	Buffer full = Buffer_createNull();

	for (U64 i = 0; i < count; ++i) {

		//Copy plaintext and additional data into writable, 16-byte aligned buffers

		if (!Test_assert(t, "Encrypt: Copy plainText", CharString_createCopy(plainTexts[i], t->alloc, &tmp, &t->err)))
			goto clean;

		if (!Test_assert(t, "Encrypt: Copy aad", Buffer_createCopy(CharString_bufferConst(aad[i]), t->alloc, &full, &t->err)))
			goto clean;

		I32x4 iv  = I32x4_zero();
		I32x4 tag = I32x4_zero();

		Buffer_memcpy(Buffer_createRef(&iv, 12), Buffer_createRefConst(ivBytes[i], 12));

		Buffer target = CharString_buffer(tmp);

		BufferEncrypt encrypt = (BufferEncrypt) {
			.target         = (Buffer *restrict) &target,
			.additionalData = (const Buffer *restrict) &full,
			.type           = type,
			.flags          = EBufferEncryptionFlags_StopCreateIv,
			.nonConstEncrypt = {
				.key = (U32 *restrict) keys[i].ptr,
				.tag = (I32x4 *restrict) &tag,
				.iv  = (I32x4 *restrict) &iv
			}
		};

		if (!Test_assert(t, "Buffer_encryptAdvanced", Buffer_encryptAdvanced(&encrypt, &t->err)))
			goto clean;

		Test_assert(t, "Encrypt: size", CharString_length(tmp) + 16 == CharString_length(results[i]));

		I32x4 tmpTag = I32x4_load4(results[i].ptr + CharString_length(tmp));
		Test_assert(t, "Encrypt: tag", !I32x4_any(I32x4_neq(tag, tmpTag)));

		Test_assert(t, "Encrypt: ciphertext",
			Buffer_eq(
				Buffer_createRefConst(results[i].ptr, CharString_length(plainTexts[i])),
				CharString_bufferConst(tmp)
			)
		);

		//Decrypt and verify

		encrypt.flags = EBufferEncryptionFlags_None;

		if (!Test_assert(t, "Buffer_decryptAdvanced", Buffer_decryptAdvanced(&encrypt, &t->err)))
			goto clean;

		Test_assert(t, "Decrypt: plainText", !Buffer_neq(CharString_bufferConst(plainTexts[i]), CharString_bufferConst(tmp)));

	clean:
		Buffer_free(&full, t->alloc);
		CharString_free(&tmp, t->alloc);
	}
}

